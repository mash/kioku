package viewoutput

import (
	"flag"
	"os"
	"testing"
)

//go:generate go test -run ^TestSkillOutputRules$ -count=1 . -args -update-skill-rules

var updateSkillRules = flag.Bool("update-skill-rules", false, "regenerate the Kioku skill's View output reference")

func TestSkillOutputRules(t *testing.T) {
	const path = "../../plugin/skills/kioku/references/view-output.md"
	want := "<!-- Generated by go generate ./internal/viewoutput. -->\n\n" + Rules()
	if *updateSkillRules {
		if err := os.WriteFile(path, []byte(want), 0644); err != nil {
			t.Fatal(err)
		}
		return
	}
	got, err := os.ReadFile(path)
	if err != nil || string(got) != want {
		t.Fatalf("View output reference needs regeneration with go generate ./internal/viewoutput: %v", err)
	}
}
